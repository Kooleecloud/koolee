/**
 * ZIP → centroid coordinates for the NYC metro, as static reference data.
 *
 * Pure data with zero imports, imported via the `@koolee/db/zip-centroids`
 * subpath — the same rule as `coverage-zips.ts`, so a client bundle that
 * reaches this module never pulls the Postgres driver in behind it.
 *
 * RUNTIME READS THE TABLE, NOT THIS FILE. `zip_centroids` is the source every
 * query goes through; this module is the payload the seed loads into it (and
 * the snapshot migration 0028 carries so its address backfill has something to
 * join against before any seed runs). Re-running the seed reconciles the table
 * back to this file, so this file is the thing to edit.
 *
 * ---------------------------------------------------------------------------
 * GENERATION SOURCE — regenerate, never hand-edit in bulk
 * ---------------------------------------------------------------------------
 * US Census Bureau, 2023 National ZCTA Gazetteer File (public domain):
 *
 *   https://www2.census.gov/geo/docs/maps-data/data/gazetteer/2023_Gazetteer/2023_Gaz_zcta_national.zip
 *
 * Tab-separated; `GEOID` is the ZCTA, `INTPTLAT`/`INTPTLONG` are the
 * internal point (a centroid pulled inside the polygon, so a C-shaped ZCTA
 * never reports a point in the sea). Filtered to ZIP prefixes 100–119 (NY:
 * the five boroughs, Long Island, lower Westchester) and 070–079 (NJ: Hudson,
 * Bergen, Essex, Union and neighbours) — the area Koolee can plausibly serve,
 * with headroom beyond today's coverage allowlist. Rounded to five decimals
 * (~1 m, far finer than a ZIP centroid deserves).
 *
 * ONE MANUAL ADDITION: `10281` (Brookfield Place / Battery Park City) is a
 * single-building ZIP and has no ZCTA at all, so it is absent from the
 * gazetteer while being present in the coverage allowlist. Its coordinate is
 * hand-entered from the street address (225 Liberty Street, New York NY).
 * `zip-centroids.test.ts` fails if any coverage ZIP loses its centroid.
 *
 * A ZIP centroid is an approximation by construction — it is the right
 * resolution for "roughly how far is this driver", and the wrong one for
 * anything that needs a doorstep. When real geocoding lands, addresses get
 * their own coordinates at insert and this becomes the fallback.
 */

